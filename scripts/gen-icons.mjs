// Generates src/lib/icons.ts containing only the icons the site uses.
// Interface symbols: Solar (Iconify). Platform marks: Simple Icons (Iconify).
import { readFileSync, writeFileSync } from "node:fs";
import { getIconData, iconToSVG } from "@iconify/utils";

const wanted = [
  "solar:play-bold",
  "solar:pause-bold",
  "solar:arrow-right-up-linear",
  "solar:arrow-down-linear",
  "solar:download-minimalistic-linear",
  "solar:letter-linear",
  "solar:map-point-linear",
  "solar:close-square-linear",
  "solar:headphones-round-linear",
  "solar:videocamera-record-linear",
  "simple-icons:instagram",
  "simple-icons:soundcloud",
  "simple-icons:youtube",
  "simple-icons:mixcloud",
  "simple-icons:audiomack",
  "simple-icons:whatsapp",
];

const sets = {};
const out = {};
for (const full of wanted) {
  const [prefix, name] = full.split(":");
  sets[prefix] ??= JSON.parse(readFileSync(`node_modules/@iconify-json/${prefix}/icons.json`, "utf8"));
  const data = getIconData(sets[prefix], name);
  if (!data) throw new Error(`Missing icon ${full}`);
  const svg = iconToSVG(data, { height: "auto" });
  out[full] = { viewBox: svg.attributes.viewBox, body: svg.body };
}

writeFileSync(
  "src/lib/icons.ts",
  `// Generated by scripts/gen-icons.mjs — do not edit by hand.\nexport const icons = ${JSON.stringify(out, null, 2)} as const;\n\nexport type IconName = keyof typeof icons;\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons`);
